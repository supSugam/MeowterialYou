/**
 * Precomputed per-logo Fastfetch configs and per-launch shell cycler script.
 */

import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import { deleteFile, writeTextFile } from '../theme/fileHelper.js';
import { scanWallpaperDirectory } from '../wallpaper/wallpaperSorter.js';
import { resolveFastfetchHomeDirs } from './fastfetchGeometry.js';
import { ensureShellRcSourced } from './shellPromptTheme.js';

const FASTFETCH_CYCLE_STUB =
  '# MeowterialYou Fastfetch cycling is disabled.\nunset -f fastfetch 2>/dev/null || true\n';

export interface FastfetchCycleSyncOptions {
  homeDir: string;
  fastfetchDir: string;
  logoDir: string;
  shouldCycle: boolean;
  buildConfigForLogo: (logoPath: string) => Record<string, unknown>;
}

function buildCycleScript(count: number): string {
  return `# Auto-generated by MeowterialYou - Fastfetch per-launch logo cycler
__meowterialyou_rotate_fastfetch() {
  local cfg_dir="$HOME/.config/meowterialyou/fastfetch-configs"
  local idx_file="$HOME/.config/meowterialyou/fastfetch-index"
  local target_cfg="$HOME/.config/fastfetch/config.jsonc"
  local count=${count}
  [ "$count" -gt 1 ] || return 0
  local idx=0
  [ -r "$idx_file" ] && read -r idx < "$idx_file" 2>/dev/null
  case "$idx" in ''|*[!0-9]*) idx=0 ;; esac
  idx=$(( (idx + 1) % count ))
  printf '%s\\n' "$idx" >| "$idx_file" 2>/dev/null
  local src_cfg="$cfg_dir/\${idx}.jsonc"
  [ -r "$src_cfg" ] && command cp -f "$src_cfg" "$target_cfg" 2>/dev/null
}

fastfetch() {
  if [ "$#" -eq 0 ]; then
    __meowterialyou_rotate_fastfetch
  fi
  command fastfetch "$@"
}

if [ -z "\${_MY_FF_STAGED:-}" ]; then
  _MY_FF_STAGED=1
  __meowterialyou_rotate_fastfetch
fi
`;
}

function removeStaleConfigs(configDir: string, keepCount: number): void {
  const dirFile = Gio.File.new_for_path(configDir);
  if (!dirFile.query_exists(null)) return;

  const enumerator = dirFile.enumerate_children('standard::name', Gio.FileQueryInfoFlags.NONE, null);
  let info: Gio.FileInfo | null;
  while ((info = enumerator.next_file(null)) !== null) {
    const name = info.get_name();
    const match = /^(\d+)\.jsonc$/.exec(name);
    if (!match || Number.parseInt(match[1] ?? '0', 10) >= keepCount) {
      deleteFile(GLib.build_filenamev([configDir, name]));
    }
  }
}

export function clearFastfetchCycleForHome(homeDir: string): void {
  const appConfigDir = GLib.build_filenamev([homeDir, '.config', 'meowterialyou']);
  removeStaleConfigs(GLib.build_filenamev([appConfigDir, 'fastfetch-configs']), 0);
  deleteFile(GLib.build_filenamev([appConfigDir, 'fastfetch-index']));
  writeTextFile(GLib.build_filenamev([appConfigDir, 'fastfetch-cycle.sh']), FASTFETCH_CYCLE_STUB);
}

export function clearFastfetchCycleConfigs(): void {
  for (const homeDir of resolveFastfetchHomeDirs()) {
    clearFastfetchCycleForHome(homeDir);
  }
}

export function syncFastfetchCycleConfigs(options: FastfetchCycleSyncOptions): void {
  const { homeDir, logoDir, shouldCycle, buildConfigForLogo } = options;
  if (!shouldCycle || !logoDir || !GLib.file_test(logoDir, GLib.FileTest.IS_DIR)) {
    clearFastfetchCycleForHome(homeDir);
    return;
  }

  const logos = scanWallpaperDirectory(logoDir, 'alphabetical-asc');
  if (logos.length < 2) {
    clearFastfetchCycleForHome(homeDir);
    return;
  }

  const appConfigDir = GLib.build_filenamev([homeDir, '.config', 'meowterialyou']);
  const cycleDir = GLib.build_filenamev([appConfigDir, 'fastfetch-configs']);
  for (let i = 0; i < logos.length; i++) {
    const config = buildConfigForLogo(logos[i]!);
    writeTextFile(
      GLib.build_filenamev([cycleDir, `${i}.jsonc`]),
      JSON.stringify(config, null, 2) + '\n'
    );
  }
  removeStaleConfigs(cycleDir, logos.length);

  const indexPath = GLib.build_filenamev([appConfigDir, 'fastfetch-index']);
  if (!GLib.file_test(indexPath, GLib.FileTest.EXISTS)) {
    writeTextFile(indexPath, '0\n');
  }
  writeTextFile(
    GLib.build_filenamev([appConfigDir, 'fastfetch-cycle.sh']),
    buildCycleScript(logos.length)
  );
  const promptPath = GLib.build_filenamev([appConfigDir, 'prompt.sh']);
  if (!GLib.file_test(promptPath, GLib.FileTest.EXISTS)) {
    writeTextFile(promptPath, `#!/bin/bash\n[ -f "$HOME/.config/meowterialyou/fastfetch-cycle.sh" ] && source "$HOME/.config/meowterialyou/fastfetch-cycle.sh"\n`);
  }
  ensureShellRcSourced(homeDir);
}
